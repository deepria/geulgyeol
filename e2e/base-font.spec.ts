import {expect,test,type Page} from '@playwright/test'
import {readFile} from 'node:fs/promises'
import {fileURLToPath} from 'node:url'
import opentype from 'opentype.js'
import {createFont,DEFAULT_SETTINGS} from '../src/font'
import {sfntTables,readBaseFont} from '../src/base-font'
import {QUICK_START,guideStrokes,SLOT_BY_ID} from '../src/hangul'

const fixture=fileURLToPath(new URL('./fixtures/base.ttf',import.meta.url))
const sample=[[150,150,.5],[300,150,.5],[300,300,.5]] as [number,number,number][]
const arrayBuffer=(bytes:Buffer)=>Uint8Array.from(bytes).buffer
async function draw(page:Page){
  const pad=page.locator('.writing-pad');await pad.scrollIntoViewIfNeeded();const box=(await pad.boundingBox())!
  await pad.dispatchEvent('pointerdown',{pointerId:1,pointerType:'pen',button:0,pressure:.5,clientX:box.x+box.width*.3,clientY:box.y+box.height*.3})
  await pad.dispatchEvent('pointermove',{pointerId:1,pointerType:'pen',pressure:.5,clientX:box.x+box.width*.65,clientY:box.y+box.height*.65})
  await pad.dispatchEvent('pointerup',{pointerId:1,pointerType:'pen',clientX:box.x+box.width*.65,clientY:box.y+box.height*.65})
}
async function saved(page:Page){await expect(page.locator('.save-state')).toContainText('저장됨');return page.evaluate(()=>JSON.parse(localStorage.getItem('geulgyeol.project.v4')!))}

test('base export preserves unselected outlines, aliases, layout and units, and loads as an actual font',async({page},info)=>{
  test.skip(info.project.name==='mobile','Identical binary export checked on desktop')
  const buffer=arrayBuffer(await readFile(fixture)),original=opentype.parse(buffer)
  const result=await createFont({'가':[sample],'나':[sample],'힣':[sample]},DEFAULT_SETTINGS,'새 글꼴',{},undefined,{buffer,targets:['나','힣']})
  const exported=opentype.parse(result)
  const converted=opentype.parse(await createFont({},DEFAULT_SETTINGS,'Baseline',{},undefined,{buffer,targets:[]}))
  expect(exported.unitsPerEm).toBe(2048)
  expect(exported.getEnglishName('fontFamily')).toBe('새 글꼴')
  expect(exported.getEnglishName('copyright')).toBe(original.getEnglishName('copyright'))
  expect(exported.getEnglishName('license')).toBe(original.getEnglishName('license'))
  for(const char of ['가','낙','A','V','f','i']){
    expect(exported.charToGlyphIndex(char)).toBe(original.charToGlyphIndex(char))
    expect(exported.charToGlyph(char).path.toPathData(1)).toBe(converted.charToGlyph(char).path.toPathData(1))
    expect(exported.charToGlyph(char).advanceWidth).toBe(original.charToGlyph(char).advanceWidth)
  }
  expect(exported.charToGlyphIndex('나')).not.toBe(exported.charToGlyphIndex('낙'))
  expect(exported.charToGlyph('나').path.toPathData()).not.toBe(original.charToGlyph('나').path.toPathData())
  expect(exported.charToGlyph('나').advanceWidth).toBe(1800)
  expect(exported.charToGlyphIndex('힣')).toBeGreaterThan(0)
  expect(exported.getKerningValue(exported.charToGlyph('A'),exported.charToGlyph('V'))).toBe(-160)
  for(const tag of ['GPOS','GSUB'])expect(sfntTables(result).get(tag)).toEqual(sfntTables(buffer).get(tag))
  let sum=0;const view=new DataView(result)
  for(let i=0;i<result.byteLength;i+=4)sum=(sum+view.getUint32(i))>>>0
  expect(sum).toBe(0xb1b0afba)
  await page.goto('/')
  expect(await page.evaluate(async data=>{const font=new FontFace('BaseExport',Uint8Array.from(data).buffer);await font.load();document.fonts.add(font);return font.status},[...new Uint8Array(result)])).toBe('loaded')
  // CFF OTF is also accepted as a subsequent base, without losing original curves.
  const second=await createFont({},DEFAULT_SETTINGS,'Second Base',{},undefined,{buffer:result,targets:[]})
  const reparsed=opentype.parse(second)
  expect(reparsed.charToGlyph('가').path.toPathData()).toBe(exported.charToGlyph('가').path.toPathData())
  expect(await readBaseFont(result,'custom.otf')).toBeTruthy()
  const tightened=opentype.parse(await createFont({},{...DEFAULT_SETTINGS,spacing:-50},'Spacing',{},undefined,{buffer,targets:[]}))
  expect(tightened.charToGlyph('\u0301').advanceWidth).toBe(0)
  const varied=buffer.slice(0),directory=new DataView(varied)
  for(let pos=12;pos<12+directory.getUint16(4)*16;pos+=16)if(directory.getUint32(pos)===0x47504f53)directory.setUint32(pos,0x66766172)
  await expect(readBaseFont(varied,'variable.ttf')).rejects.toThrow('가변 폰트')
  const components=Object.fromEntries(QUICK_START.map(id=>[id,guideStrokes(SLOT_BY_ID[id]!)]))
  const composed=opentype.parse(await createFont({},DEFAULT_SETTINGS,'Composed',components,undefined,{buffer,targets:['가']}))
  expect(composed.charToGlyph('가').path.toPathData()).not.toBe(converted.charToGlyph('가').path.toPathData())
  expect(composed.charToGlyph('나').path.toPathData()).toBe(converted.charToGlyph('나').path.toPathData())
})

test('bulk brush applies to all saved letters and components, with one undo across tabs',async({page})=>{
  const fixture={version:3,glyphs:{'안':[sample],'녕':[{points:sample,brush:'fineliner'}]},components:Object.fromEntries(QUICK_START.map(id=>[id,guideStrokes(SLOT_BY_ID[id]!)])),characters:['안','녕'],mode:'direct',settings:DEFAULT_SETTINGS,preview:'안녕가각',name:'Bulk'}
  await page.addInitScript(data=>localStorage.setItem('geulgyeol.project.v3',JSON.stringify(data)),fixture)
  await page.goto('/')
  await page.getByRole('radio',{name:'붓펜',exact:true}).click()
  await page.getByRole('button',{name:'글자·자소 전체에 적용 ↗',exact:true}).click()
  let state=await saved(page)
  const brushes=(state:any)=>Object.values({...state.glyphs,...state.components}).flat().map((stroke:any)=>stroke.brush)
  expect(new Set(brushes(state))).toEqual(new Set(['brush']))
  await page.getByRole('tab',{name:'자소 조합'}).click()
  await page.getByRole('button',{name:'전체 적용 취소',exact:true}).first().click()
  state=await saved(page)
  expect(state.glyphs['안'][0].brush).toBe('pen');expect(state.glyphs['녕'][0].brush).toBe('fineliner')
  expect(state.components[QUICK_START[0]!][0].brush).toBe('pen')
  await page.getByRole('button',{name:'글자·자소 전체에 적용 ↗',exact:true}).click()
  await saved(page);await page.reload()
  expect(new Set(brushes(await saved(page)))).toEqual(new Set(['brush']))
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})

